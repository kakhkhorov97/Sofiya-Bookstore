import type { Genre } from '@sofiya/shared';

// Demo catalogue. Every title is a real public-domain work, or (for
// PROGRAMMING) a book its authors publish under a free licence. Descriptions
// are original to this project. Pages are typical edition lengths; prices and
// stock are generated in seed.ts and are demo values only.
export interface CatalogueEntry {
  title: string;
  author: string;
  genre: Genre;
  year: number; // first publication; negative = BC
  pages: number;
  description: string;
}

type Row = [
  title: string,
  author: string,
  year: number,
  pages: number,
  description: string,
];

const shelf = (genre: Genre, rows: Row[]): CatalogueEntry[] =>
  rows.map(([title, author, year, pages, description]) => ({
    title,
    author,
    genre,
    year,
    pages,
    description,
  }));

